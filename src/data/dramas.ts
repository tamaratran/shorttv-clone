export function getDramaBySlug(slug: string): Drama | undefined {
  for (const genre of genres) {
    const found = genre.dramas.find((d) => d.slug === slug);
    if (found) return found;
  }
  return featuredDramas.find((d) => d.slug === slug);
}

export function getAllDramas(): Drama[] {
  const seen = new Set<string>();
  const all: Drama[] = [];
  for (const genre of genres) {
    for (const drama of genre.dramas) {
      if (!seen.has(drama.id)) {
        seen.add(drama.id);
        all.push(drama);
      }
    }
  }
  return all;
}
